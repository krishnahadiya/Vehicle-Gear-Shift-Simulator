/*
 * script.js - user interface only.
 * Every vehicle calculation (rpm, speed, fuel, temperature, score, shift rules)
 * is done by the C engine compiled to WebAssembly (sim.js / sim.wasm).
 * This file sends pedal/gear/ignition inputs to C and draws what C returns.
 */
(() => {
  'use strict';

  /* Must match the SimField enum order in backend/simulation.h */
  const FIELD_NAMES = ['SPEED_KMH', 'RPM', 'GEAR', 'THROTTLE', 'BRAKE', 'CLUTCH', 'FUEL_L', 'FUEL_PCT',
    'TEMP_C', 'RUNNING', 'WARN_MASK', 'SLOPE', 'FUEL_LPH', 'INST_L100', 'AVG_L100', 'DIST_KM', 'TIME_S',
    'SCORE', 'SCORE_SHIFT', 'SCORE_SMOOTH', 'SCORE_FUEL', 'TRANS_COND', 'CLUTCH_COND', 'ACCEL', 'HINT',
    'REDLINE', 'IDLE', 'MAX_SPEED', 'STALLS', 'SHIFTS_GOOD', 'SHIFTS_TOTAL', 'GRINDS', 'PAUSED',
    'HIST_TOTAL', 'FUEL_USED_L', 'SLIP_RPM'];
  const F = {};
  FIELD_NAMES.forEach((name, i) => { F[name] = i; });

  const MODE_TEXT = [
    'Forgiving clutch, anti-stall help and shift hints.',
    'Scored on low fuel use. Smooth, early upshifts win.',
    'More power and a quick clutch. Fuel target is relaxed.',
    'Rolling terrain generated by the engine. Gradient slider is locked.'
  ];
  const EVENT_CLASS = ['info', 'shift', 'warning', 'error'];
  const SLOTS = { '1': [20, 18], '2': [20, 82], '3': [50, 18], '4': [50, 82], '5': [80, 18], 'R': [80, 82], 'N': [50, 50] };
  const reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  const $ = (sel, root = document) => root.querySelector(sel);
  const clamp = (x, lo, hi) => Math.min(hi, Math.max(lo, x));
  const gearLabel = g => (g < 0 ? 'R' : g === 0 ? 'N' : String(g));
  const fmtTime = s => `${Math.floor(s / 60)}:${String(Math.floor(s % 60)).padStart(2, '0')}`;

  let api = null;
  let selVehicle = 0, selMode = 0, session = null;
  let running = false, lastFrame = 0, lastGear = 0, lastHist = 0, feedbackTimer = 0;
  const gauges = {};

  /* ---------------- boot ---------------- */
  function showBootError(msg) {
    const box = $('#boot-error');
    box.textContent = msg;
    box.hidden = false;
  }

  function bindApi(M) {
    const w = (name, ret, args) => M.cwrap(name, ret, args);
    return {
      init: w('api_init', 'number', ['number', 'number']),
      reset: w('api_reset', 'number', []),
      update: w('api_update', null, ['number']),
      setInputs: w('api_set_inputs', null, ['number', 'number', 'number']),
      setGear: w('api_set_gear', 'number', ['number']),
      ignition: w('api_ignition', 'number', ['number']),
      setSlope: w('api_set_slope', 'number', ['number']),
      setPaused: w('api_set_paused', null, ['number']),
      get: w('api_get', 'number', ['number']),
      histTotal: w('api_history_total', 'number', []),
      histGet: w('api_history_get', 'number', ['number', 'number']),
      histMsg: w('api_history_message', 'string', ['number']),
      report: w('api_report', 'string', []),
      vehicleCount: w('api_vehicle_count', 'number', []),
      vehicleName: w('api_vehicle_name', 'string', ['number']),
      vehicleDesc: w('api_vehicle_desc', 'string', ['number']),
      vehicleStat: w('api_vehicle_stat', 'number', ['number', 'number']),
      modeCount: w('api_mode_count', 'number', []),
      modeName: w('api_mode_name', 'string', ['number']),
      statusText: w('api_status_text', 'string', ['number'])
    };
  }

  function boot() {
    if (typeof createSimModule !== 'function') {
      showBootError('sim.js was not found next to index.html. Build the C backend first (see README.md), then reload.');
      return;
    }
    createSimModule().then(M => {
      api = bindApi(M);
      buildHome();
      $('#start-btn').disabled = false;
    }).catch(err => {
      const hint = location.protocol === 'file:'
        ? ' Browsers block WebAssembly on file:// pages. Start a local server with emrun (see README.md).' : '';
      showBootError(`The C engine could not start: ${err && err.message ? err.message : err}.${hint}`);
    });
  }

  /* ---------------- home screen ---------------- */
  function makeCard(title, desc, extra, onPick) {
    const b = document.createElement('button');
    b.className = 'card';
    b.setAttribute('role', 'radio');
    b.setAttribute('aria-checked', 'false');
    const s = document.createElement('strong'); s.textContent = title;
    const d = document.createElement('span'); d.textContent = desc;
    b.append(s, d);
    if (extra) { const e = document.createElement('em'); e.textContent = extra; b.append(e); }
    b.addEventListener('click', onPick);
    return b;
  }

  function selectCard(listEl, index) {
    [...listEl.children].forEach((c, i) => c.setAttribute('aria-checked', String(i === index)));
  }

  function buildHome() {
    const vList = $('#vehicle-list'), mList = $('#mode-list');
    vList.replaceChildren(); mList.replaceChildren();
    for (let i = 0; i < api.vehicleCount(); i++) {
      const extra = `${api.vehicleStat(i, 0)} kg, ${api.vehicleStat(i, 1)} Nm, redline ${api.vehicleStat(i, 2)} rpm`;
      vList.append(makeCard(api.vehicleName(i), api.vehicleDesc(i), extra, () => { selVehicle = i; selectCard(vList, i); }));
    }
    for (let i = 0; i < api.modeCount(); i++) {
      mList.append(makeCard(api.modeName(i), MODE_TEXT[i] || '', '', () => { selMode = i; selectCard(mList, i); }));
    }
    selectCard(vList, selVehicle);
    selectCard(mList, selMode);
  }

  /* ---------------- SVG gauges ---------------- */
  const NS = 'http://www.w3.org/2000/svg';
  const mk = (tag, attrs, parent) => {
    const e = document.createElementNS(NS, tag);
    Object.keys(attrs).forEach(k => e.setAttribute(k, attrs[k]));
    if (parent) parent.appendChild(e);
    return e;
  };
  const angle = f => 135 + 270 * f;                       /* 270 degree sweep */
  const point = (r, deg) => [150 + r * Math.cos(deg * Math.PI / 180), 150 + r * Math.sin(deg * Math.PI / 180)];

  function buildGauge(host, o) {
    host.replaceChildren();
    const svg = mk('svg', { viewBox: '0 0 300 300', role: 'img', 'aria-label': o.label }, host);
    mk('circle', { class: 'face', cx: 150, cy: 150, r: 142 }, svg);
    if (o.redFrom != null) {
      const a1 = angle(o.redFrom / o.max), a2 = angle(1);
      const [x1, y1] = point(124, a1), [x2, y2] = point(124, a2);
      mk('path', { class: 'red', d: `M${x1} ${y1} A124 124 0 ${a2 - a1 > 180 ? 1 : 0} 1 ${x2} ${y2}` }, svg);
    }
    for (let v = 0; v <= o.max + 1e-9; v += o.minor) {
      const major = Math.abs(v / o.major - Math.round(v / o.major)) < 1e-9;
      const a = angle(v / o.max);
      const [x1, y1] = point(major ? 110 : 118, a), [x2, y2] = point(132, a);
      mk('line', { class: major ? 'tick' : 'tick minor', x1, y1, x2, y2 }, svg);
      if (major) {
        const [tx, ty] = point(90, a);
        mk('text', { class: 'num', x: tx, y: ty }, svg).textContent = o.fmt(v);
      }
    }
    const needle = mk('g', {}, svg);
    mk('line', { class: 'needle', x1: -16, y1: 0, x2: 120, y2: 0 }, needle);
    mk('circle', { class: 'hub', cx: 150, cy: 150, r: 9 }, svg);
    const big = mk('text', { class: 'big', x: 150, y: 215 }, svg);
    mk('text', { class: 'unit', x: 150, y: 236 }, svg).textContent = o.unit;
    return { needle, big, max: o.max };
  }

  function setGauge(g, value, text) {
    const a = angle(clamp(value / g.max, 0, 1));
    g.needle.setAttribute('transform', `translate(150 150) rotate(${a})`);
    g.big.textContent = text;
  }

  function buildGauges() {
    gauges.speed = buildGauge($('#speedo'), { max: 220, major: 20, minor: 10, fmt: v => v, unit: 'km/h', label: 'Speedometer' });
    gauges.rpm = buildGauge($('#tacho'), {
      max: 8000, major: 1000, minor: 500, fmt: v => v / 1000, unit: 'rpm x 1000', label: 'Tachometer',
      redFrom: api.get(F.REDLINE)
    });
  }

  /* ---------------- gear lever ---------------- */
  function buildGate() {
    const gate = $('#gate');
    gate.querySelectorAll('.slot').forEach(s => s.remove());
    Object.keys(SLOTS).forEach(label => {
      const b = document.createElement('button');
      b.className = 'slot';
      b.textContent = label;
      b.style.left = SLOTS[label][0] + '%';
      b.style.top = SLOTS[label][1] + '%';
      b.setAttribute('aria-label', label === 'R' ? 'Reverse' : label === 'N' ? 'Neutral' : `Gear ${label}`);
      b.addEventListener('click', () => requestGear(label === 'R' ? -1 : label === 'N' ? 0 : Number(label)));
      gate.insertBefore(b, $('#knob'));
    });
  }

  function moveKnob(from, to, animate) {
    const knob = $('#knob');
    const [fx, fy] = SLOTS[from], [tx, ty] = SLOTS[to];
    knob.style.left = tx + '%';
    knob.style.top = ty + '%';
    if (!animate || reduceMotion || !knob.animate) return;
    const frames = [{ left: fx + '%', top: fy + '%' }];
    if (fx !== tx) frames.push({ left: fx + '%', top: '50%' }, { left: tx + '%', top: '50%' });
    frames.push({ left: tx + '%', top: ty + '%' });
    knob.animate(frames, { duration: 240, easing: 'ease-in-out' });
  }

  function requestGear(g) {
    if (!running) return;
    const code = api.setGear(g);               /* C validates the shift */
    if (code >= 1 && code <= 4) {
      const knob = $('#knob');
      knob.classList.remove('shake'); void knob.offsetWidth; knob.classList.add('shake');
    }
  }

  /* ---------------- inputs ---------------- */
  const pointerVal = { throttle: 0, brake: 0, clutch: 0 };
  const keyVal = { throttle: 0, brake: 0, clutch: 0 };
  const keyDown = { throttle: false, brake: false, clutch: false };
  const KEY_RATES = { throttle: [1.3, 4], brake: [3, 6], clutch: [8, 0.9] };   /* press, release per second */

  function setupPedals() {
    document.querySelectorAll('.pedal').forEach(p => {
      const name = p.dataset.pedal, track = $('.track', p);
      const set = e => { const r = track.getBoundingClientRect(); pointerVal[name] = clamp((r.bottom - e.clientY) / r.height, 0, 1); };
      track.addEventListener('pointerdown', e => { track.setPointerCapture(e.pointerId); set(e); e.preventDefault(); });
      track.addEventListener('pointermove', e => { if (track.hasPointerCapture(e.pointerId)) set(e); });
      const end = () => { pointerVal[name] = 0; };
      track.addEventListener('pointerup', end);
      track.addEventListener('pointercancel', end);
    });
  }

  function shapeKeys(dt) {
    Object.keys(keyVal).forEach(n => {
      const [up, down] = KEY_RATES[n];
      keyVal[n] = keyDown[n] ? Math.min(1, keyVal[n] + up * dt) : Math.max(0, keyVal[n] - down * dt);
    });
  }

  const PEDAL_KEYS = { w: 'throttle', arrowup: 'throttle', s: 'brake', arrowdown: 'brake', shift: 'clutch', a: 'clutch' };

  function onKey(e, down) {
    if (!$('#sim').classList.contains('is-active')) return;
    if (e.target && e.target.tagName === 'INPUT') return;
    const k = e.key.toLowerCase();
    if (PEDAL_KEYS[k]) { keyDown[PEDAL_KEYS[k]] = down; e.preventDefault(); return; }
    if (!down || e.repeat) return;
    const digit = /^(Digit|Numpad)([0-5])$/.exec(e.code);   /* e.code keeps working while Shift is held */
    if (digit) requestGear(Number(digit[2]));
    else if (k === 'r') requestGear(-1);
    else if (k === 'n') requestGear(0);
    else if (k === 'e') toggleIgnition();
    else if (k === 'p') togglePause();
  }

  /* ---------------- actions ---------------- */
  function setFeedback(text, cls) {
    const f = $('#feedback');
    f.textContent = text;
    f.className = 'feedback' + (cls ? ' ' + cls : '');
    clearTimeout(feedbackTimer);
    if (cls) feedbackTimer = setTimeout(() => { f.textContent = ''; f.className = 'feedback'; }, 3500);
  }

  function toggleIgnition() {
    if (!running) return;
    const on = api.get(F.RUNNING) === 1;
    const code = api.ignition(on ? 0 : 1);
    if (code < 0) setFeedback(api.statusText(code), 'bad');
  }

  function togglePause() {
    if (!running) return;
    const paused = api.get(F.PAUSED) === 1;
    api.setPaused(paused ? 0 : 1);
    $('#pause-overlay').hidden = paused;
    $('#pause-btn').textContent = paused ? 'Pause' : 'Resume';
  }

  function resetSession() {
    api.reset();
    api.setPaused(0);
    $('#pause-overlay').hidden = true;
    $('#pause-btn').textContent = 'Pause';
    $('#slope-input').value = 0;
    clearHistory();
    moveKnob('N', 'N', false);
    lastGear = 0;
    $('#gear-letter').textContent = 'N';
    setFeedback('Engine off. Press E or Start engine.', '');
  }

  function clearHistory() {
    $('#history-list').replaceChildren();
    lastHist = 0;
  }

  function downloadReport() {
    const blob = new Blob([api.report()], { type: 'text/plain' });
    const a = document.createElement('a');
    a.href = URL.createObjectURL(blob);
    a.download = 'gear-shift-report.txt';
    document.body.appendChild(a);
    a.click();
    a.remove();
    setTimeout(() => URL.revokeObjectURL(a.href), 1000);
  }

  function startSession() {
    const code = api.init(selVehicle, selMode);
    if (code !== 0) { showBootError(api.statusText(code)); return; }
    session = { vehicle: api.vehicleName(selVehicle), mode: api.modeName(selMode) };
    $('#home').classList.remove('is-active');
    $('#sim').classList.add('is-active');
    $('#hud-vehicle').textContent = session.vehicle;
    $('#hud-mode').textContent = session.mode + ' mode';
    const slope = $('#slope-input');
    slope.disabled = selMode === 3;
    slope.value = 0;
    buildGauges();
    buildGate();
    clearHistory();
    moveKnob('N', 'N', false);
    lastGear = 0;
    $('#gear-letter').textContent = 'N';
    $('#pause-overlay').hidden = true;
    $('#pause-btn').textContent = 'Pause';
    setFeedback('Engine off. Press E or Start engine.', '');
    running = true;
    lastFrame = performance.now();
    requestAnimationFrame(loop);
  }

  function goHome() {
    running = false;
    api.setInputs(0, 0, 0);
    $('#sim').classList.remove('is-active');
    $('#home').classList.add('is-active');
  }

  /* ---------------- render ---------------- */
  function pollHistory() {
    const total = api.histTotal();
    const list = $('#history-list');
    for (let i = lastHist; i < total; i++) {
      const time = api.histGet(i, 0);
      if (time < 0) continue;                         /* entry already overwritten in C */
      const type = api.histGet(i, 1);
      const msg = api.histMsg(i);
      const li = document.createElement('li');
      li.className = EVENT_CLASS[type] || 'info';
      const t = document.createElement('span'); t.className = 't'; t.textContent = fmtTime(time);
      const m = document.createElement('span'); m.textContent = msg;
      const d = document.createElement('small');
      d.textContent = `Gear ${gearLabel(api.histGet(i, 2))}, ${Math.round(api.histGet(i, 3))} km/h, ${Math.round(api.histGet(i, 4))} rpm`;
      li.append(t, m, d);
      list.prepend(li);
      if (type === 3) setFeedback(msg, 'bad');
      else if (type === 2) setFeedback(msg, 'warn');
      else if (type === 1) setFeedback(msg, '');
    }
    lastHist = total;
    while (list.children.length > 80) list.lastChild.remove();
  }

  function render() {
    const g = api.get(F.GEAR) | 0;
    const rpm = api.get(F.RPM), speed = Math.abs(api.get(F.SPEED_KMH));
    const running_ = api.get(F.RUNNING) === 1;

    setGauge(gauges.speed, speed, Math.round(speed));
    setGauge(gauges.rpm, rpm, Math.round(rpm));

    if (g !== lastGear) {
      moveKnob(gearLabel(lastGear), gearLabel(g), true);
      const letter = $('#gear-letter');
      letter.textContent = gearLabel(g);
      letter.classList.add('pop');
      setTimeout(() => letter.classList.remove('pop'), 150);
      lastGear = g;
    }
    const hint = api.get(F.HINT);
    $('#hint').textContent = hint === 1 ? 'Shift up' : hint === 2 ? 'Shift down' : '';

    const fuelPct = api.get(F.FUEL_PCT), temp = api.get(F.TEMP_C);
    $('#fuel-bar').style.width = fuelPct + '%';
    $('#fuel-text').textContent = `${api.get(F.FUEL_L).toFixed(1)} L`;
    $('#temp-bar').style.width = clamp((temp - 40) / 90, 0, 1) * 100 + '%';
    $('#temp-text').textContent = `${Math.round(temp)} °C`;

    const mask = api.get(F.WARN_MASK) | 0;
    document.querySelectorAll('#lights li').forEach(li => li.classList.toggle('on', (mask & Number(li.dataset.bit)) !== 0));

    ['throttle', 'brake', 'clutch'].forEach(n => {
      const v = api.get(F[n.toUpperCase()]);
      const p = $(`.pedal[data-pedal="${n}"]`);
      $('.track i', p).style.height = v * 100 + '%';
      $('.pedal-val', p).textContent = Math.round(v * 100) + '%';
    });

    const ign = $('#ignition-btn');
    ign.textContent = running_ ? 'Stop engine' : 'Start engine';
    ign.classList.toggle('on', running_);

    /* performance panel */
    const score = api.get(F.SCORE);
    const ring = $('#ring-fg');
    ring.style.strokeDashoffset = 263.9 * (1 - score / 100);
    ring.style.stroke = score >= 75 ? 'var(--good)' : score >= 50 ? 'var(--amber)' : 'var(--signal)';
    $('#score').textContent = Math.round(score);
    $('#sc-shift').style.width = api.get(F.SCORE_SHIFT) + '%';
    $('#sc-smooth').style.width = api.get(F.SCORE_SMOOTH) + '%';
    $('#sc-fuel').style.width = api.get(F.SCORE_FUEL) + '%';
    $('#st-inst').textContent = speed > 3 ? `${api.get(F.INST_L100).toFixed(1)} L/100 km` : `${api.get(F.FUEL_LPH).toFixed(1)} L/h`;
    $('#st-avg').textContent = api.get(F.DIST_KM) > 0.01 ? `${api.get(F.AVG_L100).toFixed(1)} L/100 km` : 'Not enough distance';
    $('#st-dist').textContent = `${api.get(F.DIST_KM).toFixed(2)} km`;
    $('#st-time').textContent = fmtTime(api.get(F.TIME_S));
    $('#st-top').textContent = `${Math.round(api.get(F.MAX_SPEED))} km/h`;
    $('#st-faults').textContent = `${api.get(F.STALLS)} / ${api.get(F.GRINDS)}`;
    const tc = api.get(F.TRANS_COND), cc = api.get(F.CLUTCH_COND);
    $('#trans-bar').style.width = tc + '%'; $('#trans-text').textContent = Math.round(tc) + '%';
    $('#clutch-bar').style.width = cc + '%'; $('#clutch-text').textContent = Math.round(cc) + '%';

    const slope = api.get(F.SLOPE);
    $('#slope-text').textContent = `${slope > 0 ? '+' : ''}${slope.toFixed(1)}% ${slope > 0.2 ? 'uphill' : slope < -0.2 ? 'downhill' : 'flat'}`;
    if (selMode === 3) $('#slope-input').value = Math.round(slope);

    pollHistory();
  }

  function loop(now) {
    if (!running) return;
    const dt = Math.min(0.05, (now - lastFrame) / 1000);
    lastFrame = now;
    shapeKeys(dt);
    api.setInputs(
      Math.max(pointerVal.throttle, keyVal.throttle),
      Math.max(pointerVal.brake, keyVal.brake),
      Math.max(pointerVal.clutch, keyVal.clutch));
    api.update(dt);                                   /* all physics happens in C */
    render();
    requestAnimationFrame(loop);
  }

  /* ---------------- wire up ---------------- */
  $('#start-btn').addEventListener('click', startSession);
  $('#ignition-btn').addEventListener('click', toggleIgnition);
  $('#pause-btn').addEventListener('click', togglePause);
  $('#resume-btn').addEventListener('click', togglePause);
  $('#reset-btn').addEventListener('click', resetSession);
  $('#home-btn').addEventListener('click', goHome);
  $('#report-btn').addEventListener('click', downloadReport);
  $('#slope-input').addEventListener('input', e => api.setSlope(Number(e.target.value)));
  document.addEventListener('keydown', e => onKey(e, true));
  document.addEventListener('keyup', e => onKey(e, false));
  window.addEventListener('blur', () => { Object.keys(keyDown).forEach(k => { keyDown[k] = false; }); });
  document.addEventListener('visibilitychange', () => {
    if (document.hidden && running && api.get(F.PAUSED) === 0) togglePause();
  });
  setupPedals();
  boot();
})();
